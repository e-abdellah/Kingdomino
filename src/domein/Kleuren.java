package domein;

/**
 * De {@code Kleuren} enum definieert de set van kleuren die gebruikt worden in het spel.
 * Deze kleuren kunnen gebruikt worden voor diverse doeleinden zoals het markeren van spelers,
 * gebieden op het spelbord, of andere visuele elementen waar kleuridentificatie van belang is.
 * <p>
 * Beschikbare kleuren zijn:
 * <ul>
 * <li>{@link #GROEN} - Vertegenwoordigt de kleur groen.</li>
 * <li>{@link #BLAUW} - Vertegenwoordigt de kleur blauw.</li>
 * <li>{@link #ROOS} - Vertegenwoordigt de kleur roos (roze).</li>
 * <li>{@link #GEEL} - Vertegenwoordigt de kleur geel.</li>
 * </ul>
 */
public enum Kleuren {
    /**
     * Groen
     */
    GROEN,

    /**
     * Blauw
     */
    BLAUW,

    /**
     * Roos (roze)
     */
    ROOS,

    /**
     * Geel
     */
    GEEL;
}
